import { ProcessedStudent } from '../types/student';

export interface CalendarEventItem {
  id: string;
  summary: string;
  description?: string;
  start: {
    dateTime?: string;
    date?: string;
  };
  end: {
    dateTime?: string;
    date?: string;
  };
  htmlLink?: string;
}

/**
 * Creates a visa renewal deadline or follow-up appointment in the administrator's Google Calendar.
 * (Requires explicit user confirmation before execution per Workspace skill guidelines)
 */
export async function createVisaRenewalCalendarEvent(
  accessToken: string,
  student: ProcessedStudent,
  options: {
    eventTitle?: string;
    daysAhead?: number; // Target action date (e.g. today or 7 days prior to expiry)
    appointmentType: 'renewal_deadline' | 'student_consultation' | 'emgs_submission';
    customNotes?: string;
  }
): Promise<CalendarEventItem> {
  const targetDate = new Date();
  // If scheduling consultation, default to tomorrow at 10:00 AM
  targetDate.setDate(targetDate.getDate() + (options.daysAhead ?? 1));
  targetDate.setHours(10, 0, 0, 0);

  const endDate = new Date(targetDate);
  endDate.setHours(11, 0, 0, 0);

  const title =
    options.eventTitle ||
    `[UniSIRAJ Visa Action] ${student.fullName} (${student.matricId}) - Expiry: ${student.formattedExpiryDate}`;

  const description = `UniSIRAJ Centre for International Affairs (CIA) Helpdesk
Action Notice: Visa Renewal Follow-up
---------------------------------------------
Student: ${student.fullName}
Matriculation ID: ${student.matricId}
Nationality: ${student.nationality} (${student.countryCode})
Current Visa Expiry: ${student.formattedExpiryDate} (${student.daysRemaining} days remaining)
Visa Category: ${student.visaCategory}
Faculty: ${student.faculty}
EMGS Status: ${student.emgsStatus}
Action Type: ${options.appointmentType.toUpperCase().replace('_', ' ')}

Special Notes:
${options.customNotes || student.notes || 'Routine international office compliance follow-up.'}
---------------------------------------------
Generated by UniSIRAJ CIA Helpdesk Agent Dashboard`;

  // Demo simulation mode for local testing without requiring authorized OAuth domains
  if (accessToken.startsWith('demo_') || accessToken.startsWith('mock_')) {
    await new Promise((r) => setTimeout(r, 450));
    return {
      id: `evt-simulated-${Date.now()}`,
      summary: title,
      description,
      start: { dateTime: targetDate.toISOString() },
      end: { dateTime: endDate.toISOString() },
      htmlLink: 'https://calendar.google.com',
    };
  }

  const payload = {
    summary: title,
    description,
    start: {
      dateTime: targetDate.toISOString(),
      timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
    },
    end: {
      dateTime: endDate.toISOString(),
      timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone,
    },
    reminders: {
      useDefault: false,
      overrides: [
        { method: 'email', minutes: 24 * 60 },
        { method: 'popup', minutes: 60 },
      ],
    },
  };

  const response = await fetch('https://www.googleapis.com/calendar/v3/calendars/primary/events', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(payload),
  });

  if (!response.ok) {
    const errorBody = await response.json().catch(() => ({}));
    throw new Error(
      errorBody.error?.message || `Failed to create calendar event (status ${response.status})`
    );
  }

  return response.json();
}

/**
 * Fetches upcoming calendar events from Google Calendar to show synced compliance items
 */
export async function fetchUpcomingVisaEvents(accessToken: string): Promise<CalendarEventItem[]> {
  if (accessToken.startsWith('demo_') || accessToken.startsWith('mock_')) {
    return [
      {
        id: 'cal-demo-1',
        summary: '[UniSIRAJ Visa Action] Tariq Al-Mansoor - Critical Expiry Follow-up',
        start: { dateTime: new Date(Date.now() + 86400000).toISOString() },
        end: { dateTime: new Date(Date.now() + 90000000).toISOString() },
        htmlLink: 'https://calendar.google.com',
      },
      {
        id: 'cal-demo-2',
        summary: '[UniSIRAJ Visa Action] Amina Zainab Bello - EMGS Biometric Deadline',
        start: { dateTime: new Date(Date.now() + 172800000).toISOString() },
        end: { dateTime: new Date(Date.now() + 176400000).toISOString() },
        htmlLink: 'https://calendar.google.com',
      },
    ];
  }

  const now = new Date().toISOString();
  const url = `https://www.googleapis.com/calendar/v3/calendars/primary/events?timeMin=${encodeURIComponent(
    now
  )}&maxResults=10&singleEvents=true&orderBy=startTime&q=UniSIRAJ`;

  const response = await fetch(url, {
    headers: {
      Authorization: `Bearer ${accessToken}`,
    },
  });

  if (!response.ok) {
    throw new Error(`Failed to fetch calendar events (status ${response.status})`);
  }

  const data = await response.json();
  return data.items || [];
}
